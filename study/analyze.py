#!/usr/bin/env python3
"""Statistical analysis of the MAS-vs-numpy study.

Reads data/timing.jsonl (+ optional data/timing_mt.jsonl) and writes
  data/summary.json, plots/*.png and RESULTS.md (all numbers quoted in REPORT.md).
"""
import json, os, sys
from collections import defaultdict
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
DATA, PLOTS = os.path.join(HERE, "data"), os.path.join(HERE, "plots")
SOLVERS = ["numpy", "numpy_eig", "numpy_newton", "mpsolve", "mas"]
SCALING = ["kac", "int9", "unity", "lognormal", "randroots"]
RNG = np.random.default_rng(12345)
NBOOT = 10000


def load(name):
    meta, rows = [], []
    p = os.path.join(DATA, name)
    if not os.path.exists(p):
        return meta, rows
    for line in open(p):
        r = json.loads(line)
        (rows if r.get("kind") == "case" else meta).append(r)
    return meta, rows


def gmean(x):
    return float(np.exp(np.mean(np.log(x))))


def boot_ci_gmean(logs_by_stratum, nboot=NBOOT):
    """Two-level bootstrap 95% CI of exp(mean over cells of mean log): resample the (family, n) cells,
    then the cases within each drawn cell, so the CI covers the choice of cells as well as seed noise."""
    strata = [np.asarray(v) for v in logs_by_stratum if len(v)]
    est = np.mean([s.mean() for s in strata])
    W = np.stack([s[RNG.integers(0, len(s), (nboot, len(s)))].mean(axis=1) for s in strata])  # cells x nboot
    pick = RNG.integers(0, len(strata), (nboot, len(strata)))
    bs = W[pick, np.arange(nboot)[:, None]].mean(axis=1)
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return float(np.exp(est)), float(np.exp(lo)), float(np.exp(hi))


def separated(a, b):
    """True if every timing round of a is faster than every round of b (exact one-sided
    Mann-Whitney p = 1/C(m+n, m) under exchangeability; 1/3432 for 7 vs 7 rounds)."""
    return a["t_max"] < b["t_min"]


def fmt_t(s):
    if s >= 1:
        return f"{s:.2f} s"
    if s >= 1e-3:
        return f"{s * 1e3:.2f} ms"
    return f"{s * 1e6:.0f} µs"


def fmt_e(x):
    if x == 0:
        return "0"
    return f"{x:.1e}"


def main():
    meta, rows = load("timing.jsonl")
    if not rows:
        sys.exit("no data/timing.jsonl")
    _, rows_mt = load("timing_mt.jsonl")
    os.makedirs(PLOTS, exist_ok=True)
    out, md = {}, []
    P = md.append

    m0 = meta[0] if meta else {}
    P(f"# Study results (auto-generated by analyze.py)\n")
    P(f"- cases: **{len(rows)}**, CPU: {m0.get('cpu')}, kernel {m0.get('kernel')}, numpy {m0.get('numpy')}, "
      f"python {m0.get('python')}, affinity {m0.get('affinity')}, OPENBLAS_NUM_THREADS={m0.get('openblas_threads')}\n")

    # ------------------------------------------------------------------ cells
    cells = defaultdict(list)
    for r in rows:
        cells[(r["family"], r["n"])].append(r)
    fam_order = []
    for r in rows:
        if r["family"] not in fam_order:
            fam_order.append(r["family"])
    group_of = {r["family"]: r["group"] for r in rows}

    # ------------------------------------------------------------------ headline paired tests
    def paired(base, rowsel):
        lr = [np.log(r[base]["t_med"] / r["mas"]["t_med"]) for r in rowsel if base in r]
        if not lr:
            return None
        strata = defaultdict(list)
        for r in rowsel:
            if base in r:
                strata[(r["family"], r["n"])].append(np.log(r[base]["t_med"] / r["mas"]["t_med"]))
        g, lo, hi = boot_ci_gmean(list(strata.values()))
        lr = np.array(lr)
        w = stats.wilcoxon(lr, alternative="greater") if len(lr) > 10 else None
        wins = sum(1 for r in rowsel if base in r and r["mas"]["t_med"] < r[base]["t_med"])
        dec_m = sum(1 for r in rowsel if base in r and separated(r["mas"], r[base]))
        dec_b = sum(1 for r in rowsel if base in r and separated(r[base], r["mas"]))
        return dict(n=len(lr), gmean_cells=g, ci=(lo, hi), gmean_cases=float(np.exp(lr.mean())),
                    median=float(np.exp(np.median(lr))), wilcoxon_p=(float(w.pvalue) if w else None),
                    mas_wins=wins, mas_decisive=dec_m, base_decisive=dec_b,
                    sign_p=float(stats.binomtest(wins, len(lr), 0.5, alternative="greater").pvalue))

    P("## 1. Headline: paired speed ratio t(solver)/t(MAS) — >1 means MAS faster\n")
    P("Geo-mean over (family, n) cells (each cell weighted equally), two-level bootstrap 95% CI (cells, then seeds); "
      "one-sided Wilcoxon signed-rank and sign tests on per-case log ratios; *decisive* = all 7 interleaved "
      "rounds of the winner faster than all rounds of the loser (exact p ≤ 1/3432 per case).\n")
    P("| baseline | subset | cases | geo-mean ratio [95% CI] | median | MAS wins | decisive MAS / baseline | Wilcoxon p | sign p |")
    P("|---|---|---|---|---|---|---|---|---|")
    out["paired"] = {}
    subsets = [("all", rows), ("scaling", [r for r in rows if r["group"] == "scaling"]),
               ("structured", [r for r in rows if r["group"] == "structured"]),
               ("n ≤ 20", [r for r in rows if r["n"] <= 20]), ("n ≥ 80", [r for r in rows if r["n"] >= 80])]
    for base in ["numpy", "numpy_eig", "numpy_newton", "mpsolve"]:
        for sname, sel in subsets:
            s = paired(base, sel)
            if not s:
                continue
            out["paired"][f"{base}|{sname}"] = s
            wp = "–" if s["wilcoxon_p"] is None else f"{s['wilcoxon_p']:.1e}"
            P(f"| {base} | {sname} | {s['n']} | **{s['gmean_cells']:.2f}×** [{s['ci'][0]:.2f}, {s['ci'][1]:.2f}] | "
              f"{s['median']:.2f}× | {s['mas_wins']}/{s['n']} | {s['mas_decisive']} / {s['base_decisive']} | "
              f"{wp} | {s['sign_p']:.1e} |")
    P("")

    # ------------------------------------------------------------------ per-cell table
    P("## 2. Per family and degree (median time per case, geo-mean over seeds)\n")
    P("`np/MAS` = geo-mean of t(np.roots)/t(MAS) over seeds; `eig/MAS` uses numpy's bare LAPACK eigvals "
      "(companion prebuilt, n ≤ 320). Accuracy columns: fraction of cases whose every root component is the "
      "correctly rounded double (CR), and worst max relative error over seeds.\n")
    P("| family | n | #cases | np.roots | eigvals | MAS | MPSolve | np/MAS | eig/MAS | MPS/MAS | CR np | CR MAS | worst relerr np | worst relerr MAS |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    out["cells"] = []
    for fam in fam_order:
        for n in sorted({k[1] for k in cells if k[0] == fam}):
            rs = cells[(fam, n)]
            t = {s: gmean([r[s]["t_med"] for r in rs]) for s in SOLVERS if all(s in r for r in rs)}
            ratio = lambda s: gmean([r[s]["t_med"] / r["mas"]["t_med"] for r in rs]) if s in t else None
            cr = {s: np.mean([r[s]["cr_frac"] == 1.0 and r[s]["count_ok"] for r in rs]) for s in t}
            we = {s: max(r[s]["max_relerr"] for r in rs) for s in t}
            cell = dict(family=fam, n=n, k=len(rs), t=t, r_np=ratio("numpy"), r_eig=ratio("numpy_eig"),
                        r_mps=ratio("mpsolve"), cr=cr, worst=we)
            out["cells"].append(cell)
            g = lambda s: fmt_t(t[s]) if s in t else "–"
            rnp = f"{cell['r_np']:.2f}×"
            rnp = f"**{rnp}**" if cell["r_np"] > 1 else rnp
            reig = "–" if cell["r_eig"] is None else f"{cell['r_eig']:.2f}×"
            rmps = "–" if cell["r_mps"] is None else f"{cell['r_mps']:.1f}×"
            P(f"| {fam} | {n} | {len(rs)} | {g('numpy')} | {g('numpy_eig')} | {g('mas')} | {g('mpsolve')} | "
              f"{rnp} | {reig} | {rmps} | {cr['numpy']:.2f} | {cr['mas']:.2f} | "
              f"{fmt_e(we['numpy'])} | {fmt_e(we['mas'])} |")
    P("")

    # ------------------------------------------------------------------ where numpy wins
    P("## 3. Where numpy is faster\n")
    lose_cells = [c for c in out["cells"] if c["r_np"] < 1]
    lose_eig = [c for c in out["cells"] if c["r_eig"] is not None and c["r_eig"] < 1]
    P(f"- cells where np.roots beats MAS (geo-mean): **{len(lose_cells)} / {len(out['cells'])}**")
    for c in lose_cells:
        P(f"  - {c['family']} n={c['n']}: ratio {c['r_np']:.2f} (np {fmt_t(c['t']['numpy'])} vs MAS {fmt_t(c['t']['mas'])}); "
          f"np worst relerr {fmt_e(c['worst']['numpy'])}, MAS {fmt_e(c['worst']['mas'])}")
    P(f"- cells where bare LAPACK eigvals beats MAS: **{len(lose_eig)} / {sum(c['r_eig'] is not None for c in out['cells'])}**")
    for c in lose_eig:
        P(f"  - {c['family']} n={c['n']}: ratio {c['r_eig']:.2f} (eig {fmt_t(c['t']['numpy_eig'])} vs MAS {fmt_t(c['t']['mas'])})")
    dec_np = [r for r in rows if separated(r["numpy"], r["mas"])]
    P(f"- individual cases where np.roots is *decisively* faster: {len(dec_np)} / {len(rows)}")
    for r in dec_np[:40]:
        P(f"  - {r['cid']}: np {fmt_t(r['numpy']['t_med'])} vs MAS {fmt_t(r['mas']['t_med'])} "
          f"(MAS status {r['mas'].get('status')}, np relerr {fmt_e(r['numpy']['max_relerr'])})")
    out["numpy_wins"] = dict(cells=[(c["family"], c["n"], c["r_np"]) for c in lose_cells],
                             eig_cells=[(c["family"], c["n"], c["r_eig"]) for c in lose_eig],
                             decisive_cases=[r["cid"] for r in dec_np])
    P("")

    # ------------------------------------------------------------------ scaling exponents
    P("## 4. Empirical complexity: log t = a + b·log n, fitted on n ≥ 80\n")
    P("95% CI for slope b from a bootstrap that resamples cases within each n (seed variance). "
      "Crossover n* is where the two fitted lines meet.\n")
    P("| family | solver | b (exponent) [95% CI] | t(n=1000) predicted | ")
    P("|---|---|---|---|")
    out["fits"] = {}

    def fit(fam, s, nmin=80):
        get = s if callable(s) else (lambda r, s=s: np.log(r[s]["t_med"]) if s in r else None)
        by_n = defaultdict(list)
        for r in rows:
            v = get(r) if r["family"] == fam and r["n"] >= nmin else None
            if v is not None:
                by_n[r["n"]].append(v)
        if len(by_n) < 3:
            return None
        ns = sorted(by_n)
        X = np.log(np.array(ns, float))

        def est(groups):
            y = np.array([np.mean(g) for g in groups])
            b, a = np.polyfit(X, y, 1)
            return a, b
        a, b = est([np.array(by_n[n]) for n in ns])
        nb = 4000
        Y = np.stack([np.asarray(by_n[n])[RNG.integers(0, len(by_n[n]), (nb, len(by_n[n])))].mean(axis=1)
                      for n in ns], axis=1)
        bs = np.polyfit(X, Y.T, 1)[0]
        lo, hi = np.percentile(bs, [2.5, 97.5])
        return dict(a=float(a), b=float(b), ci=(float(lo), float(hi)), ns=ns)

    for fam in SCALING:
        fits = {}
        for s in ["numpy", "numpy_eig", "mpsolve", "mas"]:
            f = fit(fam, s)
            if f:
                fits[s] = f
                P(f"| {fam} | {s} | **{f['b']:.2f}** [{f['ci'][0]:.2f}, {f['ci'][1]:.2f}] | "
                  f"{fmt_t(np.exp(f['a'] + f['b'] * np.log(1000)))} |")
        out["fits"][fam] = fits
    P("")
    P("Speed-up growth: slope of log(t_np.roots / t_MAS) against log n on the same cases (paired), i.e. "
      "the speed-up grows like n^g:\n")
    P("| family | g [95% CI] | speed-up at largest n | extrapolated speed-up n=5000 |")
    P("|---|---|---|---|")
    for fam in SCALING:
        f = fit(fam, lambda r: np.log(r["numpy"]["t_med"] / r["mas"]["t_med"]))
        if f:
            out["fits"][fam]["gap"] = f
            big = max(f["ns"])
            P(f"| {fam} | **{f['b']:.2f}** [{f['ci'][0]:.2f}, {f['ci'][1]:.2f}] | "
              f"{np.exp(f['a'] + f['b'] * np.log(big)):.0f}× (n={big}) | {np.exp(f['a'] + f['b'] * np.log(5000)):.0f}× |")
    P("")

    # ------------------------------------------------------------------ accuracy summary
    P("## 5. Accuracy against the certified Arb reference\n")
    P("CR = every root component is exactly the correctly rounded double; count = right number of roots "
      "(with multiplicity) matched; digits = −log10(max relative error), capped at 17.\n")
    P("| solver | cases | all-CR cases | count ok | median digits | worst relerr | cases relerr > 1e-6 |")
    P("|---|---|---|---|---|---|---|")
    out["accuracy"] = {}
    for s in SOLVERS:
        rs = [r for r in rows if s in r]
        if not rs:
            continue
        crs = sum(r[s]["cr_frac"] == 1.0 and r[s]["count_ok"] for r in rs)
        cnt = sum(bool(r[s]["count_ok"]) for r in rs)
        dig = [min(17.0, -np.log10(r[s]["max_relerr"])) if r[s]["max_relerr"] > 0 else 17.0 for r in rs]
        bad = sum(r[s]["max_relerr"] > 1e-6 for r in rs)
        worst = max(r[s]["max_relerr"] for r in rs)
        out["accuracy"][s] = dict(cases=len(rs), all_cr=crs, count_ok=cnt, median_digits=float(np.median(dig)),
                                  worst=worst, bad=bad)
        P(f"| {s} | {len(rs)} | {crs} ({100 * crs / len(rs):.1f}%) | {cnt} | {np.median(dig):.1f} | {fmt_e(worst)} | {bad} |")
    mrows = [r for r in rows if "mas" in r]
    mok = sum(r["mas"].get("mult_ok", False) for r in mrows)
    fb = sum(1 for r in mrows if r["mas"].get("status", 0) & 4)
    gc_ = sum(1 for r in mrows if r["mas"].get("status", 0) & 2)
    P(f"\nMAS multiplicities exactly right: {mok}/{len(mrows)}; status: exact-gcd path used in {gc_}, "
      f"multiprecision fallback in {fb} cases.\n")
    out["mas_mult_ok"] = mok
    out["mas_fallback"] = fb

    P("Per family (fraction of cases fully correctly rounded / median digits):\n")
    P("| family | " + " | ".join(SOLVERS) + " |")
    P("|---|" + "---|" * len(SOLVERS))
    for fam in fam_order:
        rs = [r for r in rows if r["family"] == fam]
        cells_ = []
        for s in SOLVERS:
            q = [r for r in rs if s in r]
            if not q:
                cells_.append("–")
                continue
            crf = np.mean([r[s]["cr_frac"] == 1.0 and r[s]["count_ok"] for r in q])
            dig = np.median([min(17.0, -np.log10(r[s]["max_relerr"])) if r[s]["max_relerr"] > 0 else 17.0 for r in q])
            cells_.append(f"{crf:.2f} / {dig:.1f}")
        P(f"| {fam} | " + " | ".join(cells_) + " |")
    P("")

    # ------------------------------------------------------------------ pareto
    P("## 5b. Pareto comparison per case (time, accuracy)\n")
    acc_key = lambda r, s: (0.0 if r[s]["cr_frac"] == 1.0 and r[s]["count_ok"] else max(r[s]["max_relerr"], 1e-300))
    dom_m = sum(1 for r in rows if r["mas"]["t_med"] <= r["numpy"]["t_med"] and acc_key(r, "mas") <= acc_key(r, "numpy")
                and (r["mas"]["t_med"] < r["numpy"]["t_med"] or acc_key(r, "mas") < acc_key(r, "numpy")))
    dom_n = sum(1 for r in rows if r["numpy"]["t_med"] <= r["mas"]["t_med"] and acc_key(r, "numpy") <= acc_key(r, "mas")
                and (r["numpy"]["t_med"] < r["mas"]["t_med"] or acc_key(r, "numpy") < acc_key(r, "mas")))
    fast_np = [r for r in rows if r["numpy"]["t_med"] < r["mas"]["t_med"]]
    P(f"- MAS Pareto-dominates np.roots (no slower, and strictly more accurate or faster) on **{dom_m}/{len(rows)}** cases; "
      f"np.roots dominates MAS on **{dom_n}** cases.")
    if fast_np:
        errs = sorted(r["numpy"]["max_relerr"] for r in fast_np)
        P(f"- On the {len(fast_np)} cases where np.roots is faster, its max relative error ranges "
          f"{fmt_e(errs[0])} … {fmt_e(errs[-1])} (median {fmt_e(errs[len(errs) // 2])}); MAS is correctly rounded on all of them.")
    out["pareto"] = dict(mas_dominates=dom_m, numpy_dominates=dom_n, numpy_faster=len(fast_np))
    P("")

    # ------------------------------------------------------------------ efficiency at equal accuracy
    P("## 6. Efficiency at equal guarantee\n")
    P("The only other solver here that targets full double accuracy with a guarantee is MPSolve "
      "(certified, multiprecision). np.roots+2 Newton steps is the cheap 'polish' fix.\n")
    for base in ["mpsolve", "numpy_newton"]:
        s = out["paired"].get(f"{base}|all")
        if s:
            a = out["accuracy"][base]
            P(f"- vs **{base}**: MAS {s['gmean_cells']:.1f}× faster (95% CI {s['ci'][0]:.1f}–{s['ci'][1]:.1f}), "
              f"MAS faster on {s['mas_wins']}/{s['n']} cases; {base} fully CR on {a['all_cr']}/{a['cases']} cases.")
    P("")

    # ------------------------------------------------------------------ multithreaded supplement
    if rows_mt:
        P("## 7. Supplement: np.roots with 2 OpenBLAS threads\n")
        base_t = {r["cid"]: r for r in rows}
        P("| case | np.roots 1 thr | np.roots 2 thr | MAS (1 thr) | np2/MAS |")
        P("|---|---|---|---|---|")
        for r in rows_mt:
            b = base_t.get(r["cid"])
            if b:
                P(f"| {r['cid']} | {fmt_t(b['numpy']['t_med'])} | {fmt_t(r['numpy']['t_med'])} | "
                  f"{fmt_t(b['mas']['t_med'])} | {r['numpy']['t_med'] / b['mas']['t_med']:.1f}× |")
        P("")

    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(md) + "\n")
    json.dump(out, open(os.path.join(DATA, "summary.json"), "w"), indent=1, default=float)
    plots(rows, out)
    print("\n".join(md))


def plots(rows, out):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    col = {"numpy": "C0", "numpy_eig": "C9", "mpsolve": "C2", "mas": "C3", "numpy_newton": "C1"}

    # time vs n, scaling families
    fig, axs = plt.subplots(1, len(SCALING), figsize=(4 * len(SCALING), 3.8), sharey=True)
    for ax, fam in zip(axs, SCALING):
        for s in ["numpy", "numpy_eig", "mpsolve", "mas"]:
            by_n = defaultdict(list)
            for r in rows:
                if r["family"] == fam and s in r:
                    by_n[r["n"]].append(r[s]["t_med"])
            if not by_n:
                continue
            ns = sorted(by_n)
            ax.loglog(ns, [gmean(by_n[n]) for n in ns], "o-", color=col[s], label=s, ms=4)
            for n in ns:
                ax.scatter([n] * len(by_n[n]), by_n[n], s=3, color=col[s], alpha=0.3)
        ns = np.array([80, 1280])
        ax.loglog(ns, 2e-3 * (ns / 320.0) ** 3, "k:", lw=0.8)
        ax.loglog(ns, 2e-4 * (ns / 320.0) ** 2, "k--", lw=0.8)
        ax.set_title(fam)
        ax.set_xlabel("degree n")
        ax.grid(True, which="both", alpha=0.2)
    axs[0].set_ylabel("time per solve [s]")
    axs[0].legend(fontsize=8, title="dotted n³, dashed n²", title_fontsize=7)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOTS, "time_vs_n.png"), dpi=130)
    plt.close(fig)

    # speedup per case
    fig, ax = plt.subplots(figsize=(8, 4.5))
    fams = sorted({r["family"] for r in rows})
    cmap = plt.get_cmap("tab20")
    for i, fam in enumerate(fams):
        rs = [r for r in rows if r["family"] == fam]
        jitter = np.exp(RNG.normal(0, 0.04, len(rs)))
        ax.scatter([r["n"] * j for r, j in zip(rs, jitter)], [r["numpy"]["t_med"] / r["mas"]["t_med"] for r in rs],
                   s=10, color=cmap(i % 20), label=fam, alpha=0.8)
    ax.axhline(1, color="k", lw=0.8)
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("degree n"); ax.set_ylabel("t(np.roots) / t(MAS)   (>1: MAS faster)")
    ax.legend(fontsize=6, ncol=2)
    ax.grid(True, which="both", alpha=0.2)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOTS, "speedup.png"), dpi=130)
    plt.close(fig)

    # accuracy vs time
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for s in ["numpy", "numpy_newton", "mpsolve", "mas"]:
        rs = [r for r in rows if s in r]
        e = np.array([max(r[s]["max_relerr"], 1e-18) for r in rs])
        ax.scatter([r[s]["t_med"] for r in rs], e, s=6, color=col[s], label=s, alpha=0.6)
    ax.axhline(2 ** -53, color="k", ls=":", lw=0.8)
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("time per solve [s]"); ax.set_ylabel("max relative error vs Arb (0 plotted at 1e-18)")
    ax.legend(fontsize=8)
    ax.grid(True, which="both", alpha=0.2)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOTS, "accuracy_vs_time.png"), dpi=130)
    plt.close(fig)


if __name__ == "__main__":
    main()
